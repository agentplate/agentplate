/**
 * Ownership-aware writes of a runtime instruction file OUTSIDE an agent worktree.
 *
 * `writeOverlay` (./overlay.ts) refuses any target that is not under
 * `/.agentplate/worktrees/`, because a project root's `.claude/CLAUDE.md`,
 * `AGENTS.md` or `GEMINI.md` belongs to the operator. The attended coordinator,
 * though, runs AT the project root, and runtimes without a system-prompt flag
 * (codex, opencode, cursor, gemini) only read their role from that file. These
 * helpers keep the same promise for that case:
 *
 * - A file is written only when nothing is at the path yet, or when the file
 *   there is one Agentplate generated (its first line is {@link GENERATED_MARKER}).
 * - Anything else — an operator's file, a symlink, a directory — is left alone.
 * - Removal is likewise limited to Agentplate-generated files.
 */

import { lstatSync, mkdirSync, readFileSync, rmSync, type Stats, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

/** First-line stamp that identifies an instruction file Agentplate generated. */
export const GENERATED_MARKER = "<!-- agentplate:generated";

const GENERATED_HEADER =
	`${GENERATED_MARKER} — written by Agentplate for this session and removed when it ` +
	"ends. Agentplate never overwrites an instruction file without this line. -->\n\n";

/** Outcome of {@link writeGeneratedInstructionFile}. */
export type GeneratedWriteResult =
	| { written: true; path: string }
	| { written: false; path: string; reason: string };

/** True if `st` is a regular file whose content starts with the generated marker. */
function isGeneratedEntry(path: string, st: Stats): boolean {
	// lstat: a symlink is never "ours", even if its target carries the marker.
	if (!st.isFile()) return false;
	return readFileSync(path, "utf8").startsWith(GENERATED_MARKER);
}

/** True if `path` is an Agentplate-generated instruction file (not a symlink). */
export function isGeneratedInstructionFile(path: string): boolean {
	const st = lstatSync(path, { throwIfNoEntry: false });
	return st !== undefined && isGeneratedEntry(path, st);
}

/**
 * Write `content` (stamped with {@link GENERATED_MARKER}) to `<dir>/<instructionPath>`
 * unless something Agentplate does not own is already there.
 *
 * A fresh file is created with the exclusive `wx` flag, so a file that appears
 * between the check and the write is never clobbered (that write throws EEXIST).
 *
 * @returns `{ written: true }` with the path, or `{ written: false }` with the
 *   reason the existing entry was left untouched.
 */
export function writeGeneratedInstructionFile(
	dir: string,
	instructionPath: string,
	content: string,
): GeneratedWriteResult {
	const path = join(dir, instructionPath);
	const st = lstatSync(path, { throwIfNoEntry: false });
	if (st !== undefined && !isGeneratedEntry(path, st)) {
		return {
			written: false,
			path,
			reason: `${instructionPath} already exists and was not generated by Agentplate`,
		};
	}
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, `${GENERATED_HEADER}${content}`, {
		encoding: "utf8",
		flag: st === undefined ? "wx" : "w",
	});
	return { written: true, path };
}

/**
 * Best-effort removal of a file written by {@link writeGeneratedInstructionFile}.
 * A file that no longer carries the marker (the operator replaced it) is kept.
 *
 * @returns true if the file was removed.
 */
export function removeGeneratedInstructionFile(path: string): boolean {
	try {
		if (!isGeneratedInstructionFile(path)) return false;
		rmSync(path);
		return true;
	} catch {
		return false;
	}
}
