import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import {
	existsSync,
	lstatSync,
	mkdirSync,
	mkdtempSync,
	readFileSync,
	rmSync,
	symlinkSync,
	writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
	GENERATED_MARKER,
	isGeneratedInstructionFile,
	removeGeneratedInstructionFile,
	writeGeneratedInstructionFile,
} from "./instruction-file.ts";

let dir: string;

beforeEach(() => {
	dir = mkdtempSync(join(tmpdir(), "agentplate-instr-"));
});

afterEach(() => {
	rmSync(dir, { recursive: true, force: true });
});

describe("writeGeneratedInstructionFile", () => {
	test("creates an absent file (and parent dirs), stamped with the marker", () => {
		const result = writeGeneratedInstructionFile(dir, join(".claude", "CLAUDE.md"), "# Role");
		const path = join(dir, ".claude", "CLAUDE.md");
		expect(result).toEqual({ written: true, path });
		const onDisk = readFileSync(path, "utf8");
		expect(onDisk.startsWith(GENERATED_MARKER)).toBe(true);
		expect(onDisk).toContain("# Role");
		expect(isGeneratedInstructionFile(path)).toBe(true);
	});

	test("never overwrites the operator's own instruction file", () => {
		const path = join(dir, "AGENTS.md");
		writeFileSync(path, "# Team rules\n", "utf8");
		const result = writeGeneratedInstructionFile(dir, "AGENTS.md", "# Coordinator");
		expect(result.written).toBe(false);
		if (!result.written) expect(result.reason).toMatch(/not generated by Agentplate/);
		expect(readFileSync(path, "utf8")).toBe("# Team rules\n");
	});

	test("refreshes a file Agentplate generated earlier (e.g. after a crash)", () => {
		writeGeneratedInstructionFile(dir, "AGENTS.md", "old role");
		const result = writeGeneratedInstructionFile(dir, "AGENTS.md", "new role");
		expect(result.written).toBe(true);
		const onDisk = readFileSync(join(dir, "AGENTS.md"), "utf8");
		expect(onDisk).toContain("new role");
		expect(onDisk).not.toContain("old role");
	});

	test("does not write through a symlink, even a dangling one", () => {
		const outside = join(dir, "outside.md");
		symlinkSync(outside, join(dir, "AGENTS.md"));
		expect(writeGeneratedInstructionFile(dir, "AGENTS.md", "role").written).toBe(false);
		expect(existsSync(outside)).toBe(false);
	});

	test("does not adopt a symlink whose target carries the marker", () => {
		const target = join(dir, "real.md");
		writeFileSync(target, `${GENERATED_MARKER} -->\nkeep me`, "utf8");
		symlinkSync(target, join(dir, "AGENTS.md"));
		expect(writeGeneratedInstructionFile(dir, "AGENTS.md", "role").written).toBe(false);
		expect(readFileSync(target, "utf8")).toContain("keep me");
	});

	test("leaves a directory at the path alone", () => {
		mkdirSync(join(dir, "GEMINI.md"));
		expect(writeGeneratedInstructionFile(dir, "GEMINI.md", "role").written).toBe(false);
		expect(lstatSync(join(dir, "GEMINI.md")).isDirectory()).toBe(true);
	});
});

describe("removeGeneratedInstructionFile", () => {
	test("removes a generated file", () => {
		const result = writeGeneratedInstructionFile(dir, "AGENTS.md", "role");
		expect(removeGeneratedInstructionFile(result.path)).toBe(true);
		expect(existsSync(result.path)).toBe(false);
	});

	test("keeps a file the operator replaced, and tolerates a missing one", () => {
		const path = join(dir, "AGENTS.md");
		writeFileSync(path, "# Mine now\n", "utf8");
		expect(removeGeneratedInstructionFile(path)).toBe(false);
		expect(readFileSync(path, "utf8")).toBe("# Mine now\n");
		expect(removeGeneratedInstructionFile(join(dir, "missing.md"))).toBe(false);
	});
});
